-- External subscriptions per tariff: upstream feeds the panel re-serves under its own
-- name. Each feed belongs to one tariff; only its subscribers get its servers, after the
-- panel's own nodes.

CREATE TABLE external_subscriptions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tariff_id    BIGINT NOT NULL REFERENCES tariffs(id) ON DELETE CASCADE,
  name         TEXT NOT NULL,
  url          TEXT NOT NULL,
  enabled      BOOLEAN NOT NULL DEFAULT true,
  interval_sec BIGINT NOT NULL DEFAULT 0,
  last_fetch   BIGINT NOT NULL DEFAULT 0,
  last_error   TEXT NOT NULL DEFAULT '',
  last_count   BIGINT NOT NULL DEFAULT 0,
  created_at   BIGINT NOT NULL,
  updated_at   BIGINT NOT NULL
);

CREATE INDEX external_subscriptions_tariff_id_idx ON external_subscriptions(tariff_id);

CREATE TABLE external_servers (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_sub_id BIGINT NOT NULL REFERENCES external_subscriptions(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  link            TEXT NOT NULL DEFAULT '',
  enabled         BOOLEAN NOT NULL DEFAULT true,
  mihomo          TEXT NOT NULL DEFAULT '{}',
  created_at      BIGINT NOT NULL
);

CREATE INDEX external_servers_external_sub_id_idx ON external_servers(external_sub_id);

