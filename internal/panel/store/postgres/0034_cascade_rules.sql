-- +goose Up
-- Cascade rules of a node: part of a listener's traffic (the match) leaves through
-- another node's relay instead of where the listener's own outbound sends it. They are
-- ordered: the first matching rule wins, and a listener's whole-traffic exit (its
-- exit_node_id) applies only to what no rule matched.

CREATE TABLE cascade_rules (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  node_id      BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  inbound_id   BIGINT REFERENCES inbounds(id) ON DELETE CASCADE, -- NULL: any listener, the relay included
  match        TEXT NOT NULL,   -- canonical "TYPE,VALUE" without a target, e.g. DOMAIN-SUFFIX,example.com
  exit_node_id BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  position     BIGINT NOT NULL DEFAULT 0,
  created_at   BIGINT NOT NULL
);

CREATE INDEX cascade_rules_node_id_idx ON cascade_rules (node_id, position);
CREATE INDEX cascade_rules_exit_node_id_idx ON cascade_rules (exit_node_id);

-- +goose Down
DROP TABLE cascade_rules;
